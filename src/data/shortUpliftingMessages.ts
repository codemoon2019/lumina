export function pickRandomShortMessage(messages: readonly string[], avoid?: string): string {
  const n = messages.length;
  if (n === 0) return "";
  if (n === 1) return messages[0] ?? "";

  let choice = messages[Math.floor(Math.random() * n)] ?? "";
  if (avoid !== undefined && n > 1) {
    let guard = 0;
    while (choice === avoid && guard++ < 32) {
      choice = messages[Math.floor(Math.random() * n)] ?? "";
    }
  }
  return choice;
}
